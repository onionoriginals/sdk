/**
 * Regenerate the bundled "First Light" example: a real Originals Protocol
 * evidence package, authored by a did:vh made for this run whose keys are
 * discarded. No network writes. Anyone can check the result offline with
 * `originals verify public/example/first-light.originals.zip`.
 *
 *   bun scripts/make-example.ts
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { MemoryStore, OriginalsSDK } from "@originals/sdk/originals";
import { generateArtwork } from "../src/sdk/artwork";
import { createLocalAuthor } from "../src/sdk/local-author";

const directory = join(import.meta.dir, "..", "public", "example");
mkdirSync(directory, { recursive: true });

// Fixed times, so the example verifies under the clocks its tests use.
const author = await createLocalAuthor(new Date("2026-10-22T04:32:13Z"));
const sdk = OriginalsSDK.create({ store: new MemoryStore(), authors: [author.evidence], clock: () => Date.parse("2026-10-22T04:32:14Z") });
const artwork = new TextEncoder().encode(generateArtwork("First Light", "Orbits", 20260706).svg);
// One resource per Original; descriptive values go in the asset state's metadata (P4.1; originals-spec #53).
const description = { title: "First Light", style: "Orbits", creator: "Originals example" };
const metadata = new TextEncoder().encode(JSON.stringify(description, null, 2));
const created = await sdk.create({
  name: "First Light",
  metadata: description,
  resource: { mediaType: "image/svg+xml", bytes: artwork },
  author: author.ref,
  signer: author.signer,
});
if (created.kind !== "original" || !created.original.validAsOf) throw new Error("the example did not verify");
const pkg = await sdk.package(created.original.did);
if (pkg.manifest.completeness !== "complete") throw new Error("the example package is not complete");

writeFileSync(join(directory, "first-light.originals.zip"), pkg.bytes);
writeFileSync(join(directory, "artwork.svg"), artwork);
writeFileSync(join(directory, "metadata.json"), metadata);
writeFileSync(
  join(import.meta.dir, "..", "src", "sdk", "example-evidence.ts"),
  `/** Generated by scripts/make-example.ts. Do not edit; regenerate instead. */\n` +
    `export const FIRST_LIGHT = ${JSON.stringify({ original: created.original.did, checkpoint: created.original.checkpoint, author: author.ref.did })} as const;\n` +
    `export const FIRST_LIGHT_ZIP_BASE64 =\n  ${JSON.stringify(Buffer.from(pkg.bytes).toString("base64"))};\n`,
);
console.log(`First Light: ${created.original.did} at ${created.original.checkpoint}`);
